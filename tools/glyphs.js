// Генератор глифов логотипа в стиле figlet-шрифта "ANSI Shadow".
//
// Буква задаётся пиксельной маской ('#' закрашено, '.' пусто), тень достраивается
// автоматически: каждая закрашенная ячейка отбрасывает вертикальную тень справа и
// горизонтальную снизу. Правила сняты с оригинального шрифта и проверяются ниже на
// его настоящих заглавных глифах.
//
// Запуск:  node tools/glyphs.js
// Вывод:   логотип целиком и JSON для вставки в объект GLYPHS в index.html.

'use strict';

function shadow(mask) {
  const h = mask.length, w = mask[0].length;
  const S = (r, c) => r >= 0 && r < h && c >= 0 && c < w && mask[r][c] === '#';
  const out = [];
  for (let r = 0; r < h; r++) {
    let line = '';
    for (let c = 0; c <= w; c++) {
      if (S(r, c)) { line += '█'; continue; }
      const up    = S(r - 1, c - 1) && !S(r - 1, c);
      const left  = S(r - 1, c - 1) && !S(r, c - 1);
      const down  = S(r, c - 1);
      const right = S(r - 1, c);
      let ch = ' ';
      if (up && left) ch = '╝';
      else if (down && right) ch = '╔';
      else if (up && down) ch = '║';
      else if (left && right) ch = '═';
      else if (down) ch = '╗';
      else if (right) ch = '╚';
      line += ch;
    }
    out.push(line);
  }
  return out;
}

// ---- самопроверка на оригинальных заглавных глифах ANSI Shadow ----
const KNOWN = {
  E: ['███████╗', '██╔════╝', '█████╗  ', '██╔══╝  ', '███████╗', '╚══════╝'],
  M: ['███╗   ███╗', '████╗ ████║', '██╔████╔██║', '██║╚██╔╝██║', '██║ ╚═╝ ██║', '╚═╝     ╚═╝'],
  P: ['██████╗ ', '██╔══██╗', '██████╔╝', '██╔═══╝ ', '██║     ', '╚═╝     '],
  D: ['██████╗ ', '██╔══██╗', '██║  ██║', '██║  ██║', '██████╔╝', '╚═════╝ '],
  A: [' █████╗ ', '██╔══██╗', '███████║', '██╔══██║', '██║  ██║', '╚═╝  ╚═╝'],
  T: ['████████╗', '╚══██╔══╝', '   ██║   ', '   ██║   ', '   ██║   ', '   ╚═╝   '],
  '2': ['██████╗ ', '╚════██╗', ' █████╔╝', '██╔═══╝ ', '███████╗', '╚══════╝'],
  // K в оригинале нарисована с одним стилистическим исключением (нет ╚ в 5-й строке),
  // поэтому в проверке не участвует.
};
let ok = true;
for (const [name, rows] of Object.entries(KNOWN)) {
  const mask = rows.map(r => r.slice(0, -1).replace(/█/g, '#').replace(/[^#]/g, '.'));
  if (shadow(mask).join('\n') !== rows.join('\n')) { ok = false; console.log('MISMATCH', name); }
}
console.log('self-test:', ok ? 'OK' : 'FAIL');

// ---- строчные буквы: 10 строк. Верхние выносные 0-6, основная высота 2-6, хвост 7-8,
//      последняя строка остаётся под тень ----
const ROWS = 10;
function glyph(rows, width) {
  const m = [];
  for (let i = 0; i < ROWS; i++) m.push(rows[i] || '.'.repeat(width));
  return m;
}
const LOWER = {
  e: glyph({ 2: '.#####.', 3: '##...##', 4: '#######', 5: '##.....', 6: '.#####.' }, 7),
  m: glyph({ 2: '########', 3: '##.##.##', 4: '##.##.##', 5: '##.##.##', 6: '##.##.##' }, 8),
  p: glyph({ 2: '######.', 3: '##...##', 4: '##...##', 5: '##...##', 6: '######.', 7: '##.....', 8: '##.....' }, 7),
  d: glyph({ 0: '.....##', 1: '.....##', 2: '.######', 3: '##...##', 4: '##...##', 5: '##...##', 6: '.######' }, 7),
  a: glyph({ 2: '.#####.', 3: '.....##', 4: '.######', 5: '##...##', 6: '.######' }, 7),
  t: glyph({ 0: '.##...', 1: '.##...', 2: '######', 3: '.##...', 4: '.##...', 5: '.##...', 6: '..####' }, 6),
  '2': glyph({ 0: '.#####.', 1: '##...##', 2: '.....##', 3: '...###.', 4: '.###...', 5: '##.....', 6: '#######' }, 7),
  k: glyph({ 0: '##.....', 1: '##.....', 2: '##...##', 3: '##..##.', 4: '#####..', 5: '##..##.', 6: '##...##' }, 7),
};

const GEN = {};
for (const [n, m] of Object.entries(LOWER)) GEN[n] = shadow(m);
// Как в оригинальной K: у диагонали k убираем лишний ╚ в 7-й строке.
GEN.k[6] = GEN.k[6].replace('██║ ╚██╗', '██║  ██╗');

const WORD = 'empdata2k';
const logo = [];
for (let r = 0; r < ROWS; r++) logo.push(WORD.split('').map(l => GEN[l][r]).join(''));
